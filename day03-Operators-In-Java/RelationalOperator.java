public class RelationalOperator {

	public static void main(String[] args) {

		int a = 10;
		int b = 20;

		boolean x = a == b;
		System.out.println(x);
		boolean y = a < b;
		System.out.println(y);
		boolean z = a > b;
		System.out.println(z);
		boolean u = a <= b;
		System.out.println(u);
		boolean w = a >= b;
		System.out.println(w);
		boolean m = a != b;
		System.out.println(m);
	}
}